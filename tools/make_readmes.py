def main():
    missing = {c: set(TEXT['en']) - set(TEXT[c]) for c, _ in LANGS if c in TEXT}
    assert all(c in TEXT for c, _ in LANGS), [c for c, _ in LANGS if c not in TEXT]
    assert not any(missing.values()), missing
    with open(os.path.join(ROOT, 'README.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(render('en'))
    out = os.path.join(ROOT, 'docs', 'readme')
    os.makedirs(out, exist_ok=True)
    for code, _ in LANGS:
        if code == 'en':
            continue
        with open(os.path.join(out, f'README.{code}.md'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(render(code))
    print(f'{len(LANGS)} README yazıldı')


