def language_bar(current, prefix_main, prefix_docs):
    links = []
    for code, name in LANGS:
        if code == current:
            links.append(f'**{name}**')
        elif code == 'en':
            links.append(f'[{name}]({prefix_main}README.md)')
        else:
            links.append(f'[{name}]({prefix_docs}README.{code}.md)')
    return ' · '.join(links)


